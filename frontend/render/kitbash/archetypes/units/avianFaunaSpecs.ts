import type { MaterialZoneId, MaterialZoneSpec } from '../../KitbashRegistry';
import type { BirdBuildSpec } from '../../greebles/organic/vertebrates';

const surface = (color: number, roughness: number): MaterialZoneSpec => ({
  color,
  roughness,
  metalness: 0,
  emissiveIntensity: 0,
});

function birdPalette(
  plumage: number,
  secondary: number,
  beakAndFeet: number,
  roughness = 0.56,
): Partial<Record<MaterialZoneId, MaterialZoneSpec>> {
  return {
    hullPrimary: surface(plumage, roughness),
    hullSecondary: surface(secondary, Math.min(0.80, roughness + 0.05)),
    frameGunmetal: surface(beakAndFeet, 0.44),
    rubberDark: surface(0x3a322d, 0.66),
    glassVisor: surface(0x16181c, 0.14),
  };
}

