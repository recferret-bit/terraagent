export type CardRenderKind =
  | 'archetype'
  | 'workFx'
  | 'combatFx'
  | 'weatherFx'
  | 'shaderFx'
  | 'customShaderFx'
  | 'projectileFx'
  | 'ringFx';

export type ArchetypeActionMode = 'idle' | 'walk' | 'work' | 'build33' | 'ruin';
export type DepositStageMode = 'full' | 'half' | 'depleted';
export type CustomShaderKind = 'water' | 'unifier' | 'daynight';

export interface EntityCardSpec {
  readonly id: string;
  readonly section: 'fleet' | 'ecology' | 'effects';
  readonly group: string;
  readonly title: string;
  readonly renderKind: CardRenderKind;
  readonly targetId: string;
  readonly badge: string;
  readonly desc: string;
  readonly footprintOrBudget: string;
  readonly actions?: ReadonlyArray<ArchetypeActionMode>;
  readonly defaultAction?: ArchetypeActionMode;
  readonly stages?: ReadonlyArray<DepositStageMode>;
  readonly shaderMode?: 'build33' | 'ruin';
  readonly shaderKind?: CustomShaderKind;
  readonly weatherKind?: 'lightning' | 'twister' | 'meteor' | 'rain';
}

