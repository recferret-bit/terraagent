// Helper for contracts.gen.mjs (run through tsx): prints the JSON-Schema snapshot of the contracts to stdout.
// Imports the kind files directly (not the generated indexes), so it works while those are stale.
import { z } from 'zod';
import { pathToFileURL } from 'node:url';
import { ClientMessage, ServerMessage } from '../../shared/contracts/src/ws';

type Def = { kind: string; wave: string; summary: string; [k: string]: unknown };
const toSchema = (s: z.ZodType) =>
  z.toJSONSchema(s, {
    io: 'input',
    unrepresentable: 'any',
    override: ({ zodSchema, jsonSchema }) => {
      if (zodSchema._zod.def.type === 'custom') Object.assign(jsonSchema, { type: 'string', contentEncoding: 'binary', description: 'engine bytes' });
    },
  });
const sortKeys = (v: unknown): unknown =>
  Array.isArray(v) ? v.map(sortKeys)
  : v && typeof v === 'object' ? Object.fromEntries(Object.keys(v).sort().map((k) => [k, sortKeys((v as Record<string, unknown>)[k])]))
  : v;

const messages = (u: { options: readonly z.ZodObject[] }) =>
  Object.fromEntries(u.options.map((o) => [String((o.shape.t as z.ZodLiteral<string>).value), toSchema(o)]));

const [, , cmdFiles = '', evtFiles = ''] = process.argv;
const load = async (files: string, exp: 'command' | 'event', schemaKey: 'args' | 'data') => {
  const out: Record<string, unknown> = {};
  for (const f of files.split(',').filter(Boolean)) {
    const def = ((await import(pathToFileURL(f).href)) as Record<string, Def>)[exp];
    const { kind, wave, summary, [schemaKey]: schema, ...meta } = def;
    out[kind] = { wave, summary, ...meta, [schemaKey]: toSchema(schema as z.ZodType) };
  }
  return out;
};

const snapshot = {
  $comment: 'GENERATED by scripts/gen/contracts.gen.mjs (npm run gen). Do not edit. A diff here means the wire contract changed: update docs/spec/PROTOCOL.md too.',
  clientMessages: messages(ClientMessage as never),
  serverMessages: messages(ServerMessage as never),
  commands: await load(cmdFiles, 'command', 'args'),
  events: await load(evtFiles, 'event', 'data'),
};
process.stdout.write(JSON.stringify(sortKeys(snapshot)));
