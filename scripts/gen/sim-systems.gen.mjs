// Sim module discovery (SIM-T-01): lists `shared/sim/src/systems/<name>/index.ts` into `index.generated.ts`.
// Code generation, not import.meta.glob: the sim runs in plain Node. Folders starting with `_` are ignored.
import { existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const DIR = 'shared/sim/src/systems';

const ident = (name) => `mod_${name.replace(/[^A-Za-z0-9]/g, '_')}`;

export async function generate(root) {
  const base = join(root, DIR);
  const names = readdirSync(base, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !e.name.startsWith('_') && existsSync(join(base, e.name, 'index.ts')))
    .map((e) => e.name)
    .sort();
  const imports = names.map((n) => `import ${ident(n)} from './${n}/index';`);
  const lines = [
    '// GENERATED by scripts/gen/sim-systems.gen.mjs: do not edit. Run `npm run gen`.',
    "import type { SimModule } from './define';",
    ...imports,
    '',
    `export const SIM_MODULES: readonly SimModule[] = [${names.map(ident).join(', ')}];`,
    '',
  ];
  return [{ path: `${DIR}/index.generated.ts`, content: lines.join('\n') }];
}
