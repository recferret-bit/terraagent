// Contract auto-discovery (PR-06, PRODUCT_WAVES §4 "registries, not edits"): one file per command/event kind in
// shared/contracts/src/{commands,events}/ → generated kind unions + registries + a JSON-Schema snapshot.
import { readdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';

const SRC = 'shared/contracts/src';
const HEADER = '// GENERATED by scripts/gen/contracts.gen.mjs (npm run gen). Do not edit.\n';
const kindFiles = (root, dir) =>
  readdirSync(join(root, SRC, dir))
    .filter((f) => f.endsWith('.ts') && !f.startsWith('_') && f !== 'define.ts' && f !== 'index.ts' && !f.endsWith('.generated.ts'))
    .sort();
const ident = (f) => f.replace(/\.ts$/, '').replace(/-(\w)/g, (_, c) => c.toUpperCase()).replace(/\W/g, '_');

function registry(files, { exp, Const, Kind, Lookup, parse }) {
  const names = files.map((f) => `${exp}_${ident(f)}`);
  const imports = files.map((f, i) => `import { ${exp} as ${names[i]} } from './${f.replace(/\.ts$/, '')}';`);
  const lines = [
    HEADER, `import { z } from 'zod';`, ...imports, '',
    `export const ${Const} = [${names.join(', ')}] as const;`, '',
    `export type ${Kind} = (typeof ${Const})[number]['kind'];`,
    `export const ${Kind.toUpperCase().replace('KIND', '_KINDS')} = [...${Const}.map((d) => d.kind)] as unknown as readonly [${Kind}, ...${Kind}[]];`,
    `export const ${Kind}Schema = z.enum(${Kind.toUpperCase().replace('KIND', '_KINDS')});`, '',
    `const BY_KIND = new Map<string, (typeof ${Const})[number]>(${Const}.map((d) => [d.kind, d]));`,
    `export type ${Kind}Def<K extends ${Kind} = ${Kind}> = Extract<(typeof ${Const})[number], { kind: K }>;`,
    `export const ${Lookup} = <K extends ${Kind}>(kind: K): ${Kind}Def<K> => BY_KIND.get(kind) as ${Kind}Def<K>;`,
    `export const has${Kind} = (kind: string): kind is ${Kind} => BY_KIND.has(kind);`,
  ];
  if (parse) lines.push('', `/** Per-kind args check (the \`cmd\` envelope only carries \`kind: string\`; unknown kinds are \`cmd.reject unknown_kind\`). */`,
    `export const parseCommandArgs = (kind: string, args: unknown) => {`,
    `  const def = BY_KIND.get(kind);`,
    `  return def ? def.args.safeParse(args) : { success: false as const, error: new z.ZodError([{ code: 'custom', path: ['kind'], message: \`unknown command kind: \${kind}\`, input: kind }]) };`,
    `};`);
  return lines.join('\n') + '\n';
}

export async function generate(root) {
  const cmds = kindFiles(root, 'commands');
  const evts = kindFiles(root, 'events');
  const abs = (dir, files) => files.map((f) => join(root, SRC, dir, f)).join(',');
  const json = execFileSync(process.execPath, ['--import', 'tsx', join(root, 'scripts/gen/contracts-snapshot.ts'), abs('commands', cmds), abs('events', evts)], {
    cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024,
  });
  return [
    { path: `${SRC}/commands/index.generated.ts`, content: registry(cmds, { exp: 'command', Const: 'COMMANDS', Kind: 'CommandKind', Lookup: 'commandDef', parse: true }) },
    { path: `${SRC}/events/index.generated.ts`, content: registry(evts, { exp: 'event', Const: 'EVENTS', Kind: 'EventKind', Lookup: 'eventDef', parse: false }) },
    { path: 'shared/contracts/schema/contracts.schema.json', content: JSON.stringify(JSON.parse(json), null, 2) + '\n' },
  ];
}
