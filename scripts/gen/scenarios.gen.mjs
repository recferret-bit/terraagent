// Scenario discovery (W00 scenario loader): lists `scenarios/*.ts` into `scenarios/index.generated.ts`.
// Files starting with `_`, `index*`, and `*.config.ts` / `*.spec.ts` are not scenarios.
import { readdirSync } from 'node:fs';
import { join } from 'node:path';

const DIR = 'scenarios';
const ident = (name) => `scn_${name.replace(/[^A-Za-z0-9]/g, '_')}`;

export async function generate(root) {
  const names = readdirSync(join(root, DIR))
    .filter((f) => f.endsWith('.ts') && !f.startsWith('_') && !f.startsWith('index') && !f.endsWith('.spec.ts') && !f.endsWith('.d.ts') && !f.includes('.config.'))
    .map((f) => f.slice(0, -3))
    .sort();
  const lines = [
    '// GENERATED by scripts/gen/scenarios.gen.mjs: do not edit. Run `npm run gen`.',
    "import type { ScenarioDef } from './_define';",
    ...names.map((n) => `import ${ident(n)} from './${n}';`),
    '',
    'export const SCENARIOS: readonly { readonly file: string; readonly def: ScenarioDef }[] = [',
    ...names.map((n) => `  { file: '${n}', def: ${ident(n)} },`),
    '];',
    '',
  ];
  return [{ path: `${DIR}/index.generated.ts`, content: lines.join('\n') }];
}
