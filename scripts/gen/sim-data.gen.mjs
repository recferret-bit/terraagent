// Data table discovery (D-35): lists `shared/sim/src/data/*.ts` table files into `index.generated.ts`.
// Files starting with `_`, `index.ts` and `*.generated.ts` are not tables.
import { readdirSync } from 'node:fs';
import { join } from 'node:path';

const DIR = 'shared/sim/src/data';
const ident = (name) => `table_${name.replace(/[^A-Za-z0-9]/g, '_')}`;

export async function generate(root) {
  const names = readdirSync(join(root, DIR))
    .filter((f) => f.endsWith('.ts') && !f.startsWith('_') && f !== 'index.ts' && !f.endsWith('.generated.ts'))
    .map((f) => f.slice(0, -3))
    .sort();
  const lines = [
    '// GENERATED by scripts/gen/sim-data.gen.mjs: do not edit. Run `npm run gen`.',
    "import type { TableDef } from './_define';",
    ...names.map((n) => `import ${ident(n)} from './${n}';`),
    '',
    `export const DATA_TABLES: readonly TableDef[] = [${names.map(ident).join(', ')}];`,
    '',
  ];
  return [{ path: `${DIR}/index.generated.ts`, content: lines.join('\n') }];
}
