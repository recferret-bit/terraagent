// Merges `prisma/_base.prisma` + every other `prisma/*.prisma` (name order, `schema.prisma` excluded) into the
// generated, committed `prisma/schema.prisma`. Used by `npm run db:gen` and by the code generation runner.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export const PRISMA_DIR = join(import.meta.dirname, '../prisma');

const HEADER = `// GENERATED by shared/db/scripts/merge-schema.mjs — DO NOT EDIT.
// Edit prisma/_base.prisma or a module file prisma/<module>.prisma, then run \`npm run db:gen\`.
`;

export function mergeSchema(dir = PRISMA_DIR) {
  const files = readdirSync(dir)
    .filter((f) => f.endsWith('.prisma') && f !== 'schema.prisma' && f !== '_base.prisma')
    .sort();
  const parts = ['_base.prisma', ...files].map((f) => `// --- ${f} ---\n${readFileSync(join(dir, f), 'utf8').trim()}\n`);
  return `${HEADER}\n${parts.join('\n')}`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(join(PRISMA_DIR, 'schema.prisma'), mergeSchema());
  console.log('merged → shared/db/prisma/schema.prisma');
}
