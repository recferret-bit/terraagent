import { MOCK_ACCOUNT_ROOT, MOCK_CARGO_CONTRACT, MOCK_RELAYER_ACCOUNT, storageDepositOpId } from '@terra/contracts';
import type { PrismaClient, TransactionClient } from '@terra/db';
import { withTransaction } from '@terra/db';
import { ChainOutboxRepository } from '../application/outbox/chain-outbox.repository.js';
import type { ColonyKeyRow, KeyStore } from '../keystore/keys.js';
import { deriveAccountName, deriveSocialAccountName, isAutoGeneratedSocialHandle } from './account-name.js';
import { colonyAccountCandidates, colonyNameBudget } from './colony-account-id.js';

/** Extra attempts after a unique clash (two logins, or login racing `colonyFounded`). */
const RACE_RETRIES = 4;
const PLAYER_SLOT = 'player';
const PRE_SEALED_KEYS = new Map<string, ColonyKeyRow>();

/**
 * Registers a KEK-sealed key row already created on-chain (e.g. by `TestnetIdentityAdapter.createNamedAccount`)
 * so `ensurePlayerRow` persists the exact on-chain keypair rather than generating a mismatched second key.
 */
export function registerPreSealedAccountKey(accountId: string, row: ColonyKeyRow): void {
  const { publicKey, encryptedSecret, kekVersion } = row;
  PRE_SEALED_KEYS.set(accountId, { publicKey, encryptedSecret, kekVersion });
}

export function getPreSealedAccountKey(accountId: string): ColonyKeyRow | undefined {
  return PRE_SEALED_KEYS.get(accountId);
}

export interface EnsureColonyAccountsInput {
  readonly playerId: string;
  readonly subject: string;
  /** Named account id from `createNamedAccount` (or the social row). Owner of every new colony row. */
  readonly ownerAccountId: string;
  /** When set, only these colonies. When omitted, every `core.colony` of the player. */
  readonly colonyIds?: readonly string[];
  readonly envSource?: Record<string, string | undefined>;
}

/**
 * Idempotent player row (`slot: 'player'`) plus one row per colony (`slot` = colony id).
 * A row that already exists keeps its account id and its key. The ed25519 seed is never written.
 * Each colony row enqueues one relayer-paid `storage_deposit` in the same transaction. The player row does not.
 */
export async function ensureColonyAccounts(
  prisma: PrismaClient,
  keys: KeyStore,
  input: EnsureColonyAccountsInput,
): Promise<void> {
  const outbox = new ChainOutboxRepository(prisma);
  for (let attempt = 0; ; attempt += 1) {
    try {
      await withTransaction(prisma, (tx) => writeAccounts(tx, keys, input, outbox));
      return;
    } catch (e) {
      if (!isUnique(e) || attempt >= RACE_RETRIES) {
        if (isUnique(e)) throw new Error('colony account id is already used', { cause: e });
        throw e;
      }
    }
  }
}

async function writeAccounts(
  tx: TransactionClient,
  keys: KeyStore,
  input: EnsureColonyAccountsInput,
  outbox: ChainOutboxRepository,
): Promise<void> {
  const ownerAccountId = await ensurePlayerRow(tx, keys, input.playerId, input.ownerAccountId);
  const colonyIds = input.colonyIds ?? (await idsOf(tx, input.playerId));
  const rawStem = ownerAccountId.split('.')[0] ?? '';
  const ownerStem = /^[0-9a-f]{64}$/i.test(ownerAccountId) ? `acct-${ownerAccountId.slice(0, 8)}` : rawStem;
  const playerName = !ownerStem || isAutoGeneratedSocialHandle(ownerStem, input.subject)
    ? deriveSocialAccountName({ subject: input.subject })
    : deriveAccountName(ownerStem);
  const seen = new Set<string>();
  for (const colonyId of colonyIds) {
    if (seen.has(colonyId)) continue;
    seen.add(colonyId);
    await ensureColonyRow(
      tx,
      keys,
      { playerId: input.playerId, colonyId, playerName, ownerAccountId, envSource: input.envSource },
      outbox,
    );
  }
}

async function idsOf(tx: TransactionClient, playerId: string): Promise<string[]> {
  const rows = await tx.colony.findMany({ where: { playerId }, select: { id: true } });
  return rows.map((row) => row.id);
}

/** Returns the stored player account id (the first write wins; a later login must not rotate it). */
async function ensurePlayerRow(tx: TransactionClient, keys: KeyStore, playerId: string, ownerAccountId: string): Promise<string> {
  const existing = await tx.nearColonyAccount.findUnique({
    where: { playerId_slot: { playerId, slot: PLAYER_SLOT } },
    select: { accountId: true },
  });
  if (existing) {
    await upsertMock(tx, existing.accountId, 'named', null);
    return existing.accountId;
  }
  const sealed = getPreSealedAccountKey(ownerAccountId) ?? seal(keys);
  await tx.nearColonyAccount.create({
    data: {
      accountId: ownerAccountId,
      playerId,
      slot: PLAYER_SLOT,
      colonyId: null,
      ownerAccountId,
      ...sealed,
    },
  });
  await upsertMock(tx, ownerAccountId, 'named', sealed.publicKey);
  return ownerAccountId;
}

async function ensureColonyRow(
  tx: TransactionClient,
  keys: KeyStore,
  input: {
    playerId: string;
    colonyId: string;
    playerName: string;
    ownerAccountId: string;
    envSource?: Record<string, string | undefined>;
  },
  outbox: ChainOutboxRepository,
): Promise<void> {
  const existing = await tx.nearColonyAccount.findUnique({
    where: { playerId_slot: { playerId: input.playerId, slot: input.colonyId } },
    select: { accountId: true },
  });
  if (existing) {
    await upsertMock(tx, existing.accountId, 'colony', null);
    await enqueueStorageDeposit(outbox, tx, existing.accountId);
    return;
  }
  const accountId = await freeColonyAccountId(
    tx,
    input.colonyId,
    input.playerName,
    input.ownerAccountId,
    input.envSource,
  );
  const sealed = seal(keys);
  await tx.nearColonyAccount.create({
    data: {
      accountId,
      playerId: input.playerId,
      slot: input.colonyId,
      colonyId: input.colonyId,
      ownerAccountId: input.ownerAccountId,
      ...sealed,
    },
  });
  await upsertMock(tx, accountId, 'colony', sealed.publicKey);
  await enqueueStorageDeposit(outbox, tx, accountId);
}

/** One NEP-145 deposit per colony account. Insert-or-ignore on the opId, so a replay still enqueues when the outbox row is missing. */
async function enqueueStorageDeposit(outbox: ChainOutboxRepository, tx: TransactionClient, accountId: string): Promise<void> {
  await outbox.enqueue({
    opId: storageDepositOpId(accountId),
    port: 'Relayer',
    method: 'submitMetaTx',
    payload: {
      signerId: MOCK_RELAYER_ACCOUNT,
      receiverId: MOCK_CARGO_CONTRACT,
      signedDelegate: JSON.stringify({ action: 'storage_deposit', account_id: accountId }),
    },
  }, tx);
}

export function accountRootFromOwner(
  ownerAccountId: string,
  colonyId: string,
  envSource: Record<string, string | undefined> = process.env,
): string {
  const configuredRoot = envSource.NEAR_ROOT_ACCOUNT?.trim();
  if (ownerAccountId.endsWith('.testnet') || ownerAccountId.endsWith('.near')) {
    const isMainnet = ownerAccountId.endsWith('.near');
    const fallbackRoot = isMainnet
      ? (configuredRoot?.endsWith('.near') ? configuredRoot : 'terraagent.near')
      : (configuredRoot?.endsWith('.testnet') ? configuredRoot : 'terraagent.testnet');
    const ownerStemLen = (ownerAccountId.split('.')[0] ?? '').length;
    const ownerParent = ownerAccountId.split('.').slice(1).join('.');
    if (ownerParent.includes('.') && colonyNameBudget(colonyId, ownerParent) >= Math.max(4, ownerStemLen)) {
      return ownerParent;
    }
    return fallbackRoot;
  }
  if (/^[0-9a-f]{64}$/i.test(ownerAccountId)) {
    const nearMode = envSource.NEAR_MODE?.trim().toLowerCase();
    if (nearMode === 'mock') return MOCK_ACCOUNT_ROOT;
    if (nearMode === 'mainnet' || configuredRoot?.endsWith('.near')) {
      return configuredRoot?.endsWith('.near') ? configuredRoot : 'terraagent.near';
    }
    return configuredRoot?.endsWith('.testnet') ? configuredRoot : 'terraagent.testnet';
  }
  return MOCK_ACCOUNT_ROOT;
}

async function freeColonyAccountId(
  tx: TransactionClient,
  colonyId: string,
  playerName: string,
  ownerAccountId: string,
  envSource?: Record<string, string | undefined>,
): Promise<string> {
  const candidates = colonyAccountCandidates(colonyId, playerName, accountRootFromOwner(ownerAccountId, colonyId, envSource));
  const where = { accountId: { in: [...candidates] } };
  const [near, mock] = await Promise.all([
    tx.nearColonyAccount.findMany({ where, select: { accountId: true } }),
    tx.mockChainAccount.findMany({ where, select: { accountId: true } }),
  ]);
  const used = new Set([...near, ...mock].map((row) => row.accountId));
  const free = candidates.find((id) => !used.has(id));
  if (!free) throw new Error('colony account id is already used');
  return free;
}

/** `publicKey` is set only on insert. An existing mock row (the W06-05 named account) is left as it is. */
async function upsertMock(tx: TransactionClient, accountId: string, kind: 'named' | 'colony', publicKey: string | null): Promise<void> {
  await tx.mockChainAccount.upsert({
    where: { accountId },
    create: publicKey ? { accountId, kind, publicKey } : { accountId, kind },
    update: {},
  });
}

/** Persist `row` only. The seed on `generate()` is not copied into the returned object. */
function seal(keys: KeyStore): ColonyKeyRow {
  const { publicKey, encryptedSecret, kekVersion } = keys.generate().row;
  return { publicKey, encryptedSecret, kekVersion };
}

function isUnique(e: unknown): boolean {
  return typeof e === 'object' && e !== null && (e as { code?: unknown }).code === 'P2002';
}
