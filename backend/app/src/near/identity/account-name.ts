import { NAMED_LABEL_FALLBACK, NAMED_LABEL_MAX, withNumericSuffix } from './account-allocate.js';

// Named-account label (NEAR §2): the `{name}` segment of `{name}.terraagent.near`.
// 2–32 chars of `[a-z0-9-]`, never leading, trailing, or doubled `-` (AccountId rejects those).

const MIN_LABEL = 2;
const MAX_LABEL = NAMED_LABEL_MAX;
const FALLBACK = NAMED_LABEL_FALLBACK;
const MAX_SUFFIX = 20;
const GUILD_PREFIX = 'guild-';

/** Exact reserved labels. Anything that starts with `guild-` is reserved as well. */
const RESERVED_EXACT: ReadonlySet<string> = new Set([
  'relayer',
  'minter',
  'pilots',
  'protocol',
  'res',
  'deed',
  'bounty',
  'staking',
  'dao',
  'treasury',
  'agents',
  'npc',
  'admin',
  'root',
  'system',
  'near',
  'intents',
  'terraagent',
]);

/** True for an exact reserved label, or any label that starts with `guild-`. */
export function isReservedAccountName(name: string): boolean {
  return RESERVED_EXACT.has(name) || name.startsWith(GUILD_PREFIX);
}

/** Lowercase, collapse every non-`[a-z0-9]` run to one `-`, trim hyphens, then clamp to 2–32. */
function cleanAccountLabel(raw: string): string {
  let name = raw.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
  if (name.length > MAX_LABEL) name = name.slice(0, MAX_LABEL).replace(/-+$/, '');
  return name.length < MIN_LABEL ? FALLBACK : name;
}

/** `base-1`, then `base-2` … `base-20`. Reserved words have no hyphen, so `-1` is free; 20 is the stop. */
function unreservedSuffix(base: string): string {
  for (let n = 1; n <= MAX_SUFFIX; n++) {
    const candidate = withNumericSuffix(base, n);
    if (!isReservedAccountName(candidate)) return candidate;
  }
  return withNumericSuffix(FALLBACK, 1);
}

/**
 * Label from a display name.
 * A `guild-` prefix is dropped and cleaned again (empty or one character becomes `pilot`).
 * Any other reserved label gets `-1`, then `-2`, … up to `-20`.
 */
export function deriveAccountName(raw: string): string {
  const cleaned = cleanAccountLabel(raw);
  if (!isReservedAccountName(cleaned)) return cleaned;
  if (cleaned.startsWith(GUILD_PREFIX)) return deriveAccountName(cleaned.slice(GUILD_PREFIX.length));
  return unreservedSuffix(cleaned);
}

export interface SocialNameHints {
  readonly subject: string;
  readonly email?: string | null | undefined;
  readonly preferredName?: string | null | undefined;
}

function usableStem(raw: string | null | undefined): string | null {
  if (!raw) return null;
  const trimmed = raw.trim().replace(/^@+/, '');
  if (!trimmed || trimmed.includes('|')) return null;
  const local = (trimmed.includes('@') ? (trimmed.split('@')[0] ?? '') : trimmed).trim();
  return local.replace(/[^a-z0-9]/gi, '').length >= MIN_LABEL ? local : null;
}

/**
 * Derives a human-readable pilot handle / NEAR account stem from OIDC profile hints (`preferredName`, `email`
 * local-part) while keeping opaque OAuth provider IDs (`google-oauth2|106920817...`, `twitter|...`) out of names.
 */
export function deriveSocialAccountName(input: SocialNameHints): string {
  const fromPreferred = usableStem(input.preferredName);
  if (fromPreferred) return deriveAccountName(fromPreferred);

  const fromEmail = usableStem(input.email);
  if (fromEmail) return deriveAccountName(fromEmail);

  const sub = input.subject.trim();
  if (sub.toLowerCase().startsWith('email:')) {
    const emailLocal = usableStem(sub.slice(6));
    if (emailLocal) return deriveAccountName(emailLocal);
  }
  if (sub.includes('|')) {
    const tail = (sub.split('|').pop() ?? '').trim();
    if (/^\d+$/.test(tail) || /^[0-9a-f]{20,}$/i.test(tail)) {
      return deriveAccountName(`${FALLBACK}-${tail.slice(-6)}`);
    }
    if (tail.replace(/[^a-z0-9]/gi, '').length >= MIN_LABEL) {
      return deriveAccountName(tail);
    }
    return FALLBACK;
  }
  return deriveAccountName(sub);
}

const LEGACY_OAUTH_HANDLE = /^(google-oauth2|twitter|oauth2|auth0|apple|windowslive|github)-/i;
const GUEST_HANDLE = /^Colonist-[A-Z0-9]{4}$/i;
const FALLBACK_ID_HANDLE = /^pilot-[0-9a-f]{4,6}(-[A-Z0-9]{4})?$/i;

/** True when `handle` is an auto-assigned guest or raw OAuth-subject handle that social login should upgrade. */
export function isAutoGeneratedSocialHandle(handle: string, subject?: string): boolean {
  if (GUEST_HANDLE.test(handle) || LEGACY_OAUTH_HANDLE.test(handle) || FALLBACK_ID_HANDLE.test(handle)) {
    return true;
  }
  if (subject && (subject.includes('|') || subject.toLowerCase().startsWith('email:'))) {
    const legacy = deriveAccountName(subject);
    if (handle === legacy || handle.startsWith(`${legacy.slice(0, 27)}-`)) return true;
  }
  return false;
}
