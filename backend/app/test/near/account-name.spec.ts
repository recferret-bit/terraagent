import { describe, expect, it } from 'vitest';
import {
  deriveAccountName,
  deriveSocialAccountName,
  isAutoGeneratedSocialHandle,
  isReservedAccountName,
} from '../../src/near/identity/account-name';

const LABEL = /^[a-z0-9-]{2,32}$/;
const RESERVED = ['relayer', 'minter', 'npc', 'admin', 'root', 'system', 'near', 'intents', 'terraagent'] as const;

describe('deriveAccountName', () => {
  it('turns "Test Pilot!" into test-pilot', () => {
    expect(deriveAccountName('Test Pilot!')).toBe('test-pilot');
  });

  it('turns "relayer" into relayer-1', () => {
    expect(deriveAccountName('relayer')).toBe('relayer-1');
  });

  it('truncates a 40-character name to 32', () => {
    expect(deriveAccountName('a'.repeat(40))).toBe('a'.repeat(32));
    expect(deriveAccountName('a'.repeat(40))).toHaveLength(32);
  });

  it('does not leave a guild-trader label starting with guild-', () => {
    const name = deriveAccountName('guild-trader');
    expect(name.startsWith('guild-')).toBe(false);
    expect(name).toBe('trader');
  });

  it('uses pilot for an empty string and for "!!"', () => {
    expect(deriveAccountName('')).toBe('pilot');
    expect(deriveAccountName('!!')).toBe('pilot');
  });

  it('suffixes every exact reserved name and drops a guild- prefix before that', () => {
    for (const reserved of RESERVED) {
      expect(isReservedAccountName(reserved)).toBe(true);
      expect(deriveAccountName(reserved)).toBe(`${reserved}-1`);
      expect(deriveAccountName(`guild-${reserved}`)).toBe(`${reserved}-1`);
    }
    expect(isReservedAccountName('guild-trader')).toBe(true);
    expect(isReservedAccountName('test-pilot')).toBe(false);
  });

  it('strips a hyphen left by the 32-character cut', () => {
    expect(deriveAccountName(`${'b'.repeat(31)}!${'c'.repeat(10)}`)).toBe('b'.repeat(31));
  });

  it('returns a legal unreserved label', () => {
    for (const raw of ['Test Pilot!', 'relayer', 'a'.repeat(40), 'guild-trader', '', '!!', 'guild-guild-trader']) {
      const name = deriveAccountName(raw);
      expect(name).toMatch(LABEL);
      expect(name.startsWith('guild-')).toBe(false);
      expect(isReservedAccountName(name)).toBe(false);
    }
  });
});

describe('deriveSocialAccountName & isAutoGeneratedSocialHandle', () => {
  it('uses preferredName or email local-part instead of raw google-oauth2| or twitter| subject IDs', () => {
    expect(
      deriveSocialAccountName({
        subject: 'google-oauth2|106920817337195603999',
        email: 'recferret@gmail.com',
        preferredName: 'recferret',
      }),
    ).toBe('recferret');

    expect(
      deriveSocialAccountName({
        subject: 'google-oauth2|106920817337195603999',
        email: 'commander.one@terraagent.fun',
      }),
    ).toBe('commander-one');

    expect(
      deriveSocialAccountName({
        subject: 'twitter|987654321',
        email: null,
        preferredName: '@FerretRec',
      }),
    ).toBe('ferretrec');

    expect(
      deriveSocialAccountName({
        subject: 'email:pilot.alpha@terraagent.fun',
        email: 'pilot.alpha@terraagent.fun',
      }),
    ).toBe('pilot-alpha');
  });

  it('falls back to a short pilot-XXXXXX stem when an OAuth subject has no profile name or email', () => {
    expect(
      deriveSocialAccountName({
        subject: 'google-oauth2|106920817337195603',
        email: null,
      }),
    ).toBe('pilot-195603');
    expect(deriveSocialAccountName({ subject: 'test-pilot', email: null })).toBe('test-pilot');
  });

  it('identifies guest and legacy raw OAuth handles for automatic upgrade without touching custom handles', () => {
    expect(isAutoGeneratedSocialHandle('Colonist-4F9A')).toBe(true);
    expect(isAutoGeneratedSocialHandle('google-oauth2-106920817337195603', 'google-oauth2|106920817337195603999')).toBe(true);
    expect(isAutoGeneratedSocialHandle('twitter-987654321', 'twitter|987654321')).toBe(true);
    expect(isAutoGeneratedSocialHandle('pilot-195603')).toBe(true);
    expect(isAutoGeneratedSocialHandle('recferret', 'google-oauth2|106920817337195603999')).toBe(false);
    expect(isAutoGeneratedSocialHandle('custom-commander', 'twitter|987654321')).toBe(false);
  });
});
